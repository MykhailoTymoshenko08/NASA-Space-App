import ee
import geemap
import pandas as pd
import geopandas as gpd

try:
    ee.Initialize(project='ee-kokoshalina')
except Exception:
    ee.Authenticate()
    ee.Initialize(project='ee-kokoshalina')

FIELDS_PATH = 'fields.geojson'
OUT_LONG = 'smap_monthly_long.csv'    # field_id, date, year, month, smap_rootzone
OUT_WIDE = 'smap_monthly_wide.csv'    # рядок = поле, колонка = місяць
START_YEAR, START_MONTH = 2015, 4     # перший повний місяць
BATCH = 300                           # полів за один запит (ліміт GEE 5000 записів)

# 1. Центроїди полів (піксель SMAP ~11 км більший за поле)
gdf = gpd.read_file(FIELDS_PATH).to_crs(4326)
ids = gdf['field_id'].tolist()
fields_fc = geemap.gdf_to_ee(gdf[['field_id', 'geometry']])
points_fc = fields_fc.map(
    lambda f: ee.Feature(f.geometry().centroid(1)).copyProperties(f, ['field_id'])
)

# 2. Колекція та останній повний місяць
smap = ee.ImageCollection('NASA/SMAP/SPL4SMGP/007').select('sm_rootzone')
last = pd.Timestamp(smap.sort('system:time_start', False).first().date().format('YYYY-MM-dd').getInfo())
last_full = (last + pd.Timedelta(days=1)).to_period('M') - 1   # якщо місяць ще не закінчився, беремо попередній
print('Остання дата SMAP:', last.date(), '| останній повний місяць:', last_full)

months = pd.period_range(f'{START_YEAR}-{START_MONTH:02d}', last_full, freq='M')

def monthly_stats(year, month_list, pts):
    def per_month(m):
        start = ee.Date.fromYMD(year, m, 1)
        img = smap.filterDate(start, start.advance(1, 'month')).mean().rename('smap_rootzone')
        fc = img.reduceRegions(
            collection=pts,
            reducer=ee.Reducer.mean().setOutputs(['smap_rootzone']),   # <- явна назва
            scale=11000, crs='EPSG:4326')
        return fc.map(lambda f: f.set({'year': year, 'month': m}))
    return ee.FeatureCollection(ee.List(month_list).map(per_month)).flatten()

rows = []
for year in sorted({p.year for p in months}):
    month_list = [p.month for p in months if p.year == year]
    for i in range(0, len(ids), BATCH):
        pts = points_fc.filter(ee.Filter.inList('field_id', ids[i:i + BATCH]))
        fc = monthly_stats(year, month_list, pts)
        d = geemap.ee_to_df(fc)
        if 'smap_rootzone' in d:
            rows.append(d[['field_id', 'year', 'month', 'smap_rootzone']])
    print('готово:', year)

df = pd.concat(rows, ignore_index=True).dropna(subset=['smap_rootzone'])
df['date'] = pd.to_datetime(dict(year=df['year'], month=df['month'], day=1)).dt.strftime('%Y-%m')
df['smap_rootzone'] = df['smap_rootzone'].round(3)
df = df[['field_id', 'date', 'year', 'month', 'smap_rootzone']].sort_values(['field_id', 'date'])

# 4. Збереження: довга і широка таблиці
df.to_csv(OUT_LONG, index=False)
wide = df.pivot(index='field_id', columns='date', values='smap_rootzone')
wide.to_csv(OUT_WIDE)

print(df.head(12).to_string(index=False))
print('Рядків:', len(df), '| місяців:', df['date'].nunique(), '| полів:', df['field_id'].nunique())