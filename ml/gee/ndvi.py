import ee
import geemap
import pandas as pd
import geopandas as gpd

try:
    ee.Initialize(project='ee-kokoshalina')
except Exception:
    ee.Authenticate()
    ee.Initialize(project='ee-kokoshalina')

FIELDS_PATH = 'fields.geojson'
OUT_DAILY = 'hls_ndvi_daily.csv'          # field_id, date, ndvi, cloud_frac
OUT_LONG = 'hls_ndvi_monthly_long.csv'    # field_id, date, year, month, ndvi_hls, n_obs
OUT_WIDE = 'hls_ndvi_monthly_wide.csv'    # рядок = поле, колонка = місяць
START_YEAR = 2015
CLOUD_MAX = 0.15                          # допустима хмарність усередині полігона
SCALE = 30

BATCH = 300                               # fields per request (GEE returns at most 5000 records per getInfo)

# --- 1. Поля (повні полігони) ---
gdf = gpd.read_file(FIELDS_PATH).to_crs(4326)
gdf['geometry'] = gdf.geometry.make_valid()
gdf['field_id'] = gdf['field_id'].astype(str)
ids = gdf['field_id'].tolist()
fields_all = geemap.gdf_to_ee(gdf[['field_id', 'geometry']])

CLOUD_BITS = (1 << 1) | (1 << 2) | (1 << 3)
SNOW_BIT = 1 << 4

def daily_image(col_all, d):
    """Мозаїка всіх знімків за добу d ('YYYY-MM-dd')."""
    start = ee.Date(d)
    mos = col_all.filterDate(start, start.advance(1, 'day')).mosaic()
    fm = mos.select('Fmask').unmask(2)             # немає покриття -> вважаємо хмарою
    cloud = fm.bitwiseAnd(CLOUD_BITS).neq(0)
    snow = fm.bitwiseAnd(SNOW_BIT).neq(0)
    ndvi = (mos.normalizedDifference(['B5', 'B4']).rename('ndvi')
            .updateMask(cloud.Not().And(snow.Not())))
    return ndvi.addBands(cloud.rename('cloud').toFloat()).set('date', d)

def period_table(col_all, fields, start, end):
    """Поле x доба -> ndvi, cloud за період [start, end) для однієї пачки полів."""
    col = col_all.filterDate(start, end)
    days = (col.aggregate_array('system:time_start')
            .map(lambda t: ee.Date(t).format('YYYY-MM-dd'))
            .distinct())
    daily = ee.ImageCollection.fromImages(days.map(lambda d: daily_image(col_all, d)))

    def reduce(img):
        fc = img.reduceRegions(collection=fields, reducer=ee.Reducer.mean(), scale=SCALE)
        return fc.map(lambda f: f.set('date', img.get('date')))

    return daily.map(reduce).flatten()

def fetch(batch_ids, start, end):
    """Одна пачка полів за один місяць -> DataFrame. Якщо GEE впирається в ліміт 5000 записів, пачка ділиться навпіл."""
    fields = fields_all.filter(ee.Filter.inList('field_id', batch_ids))
    col_all = (ee.ImageCollection('NASA/HLS/HLSL30/v002')
               .filterBounds(fields.geometry())
               .select(['B4', 'B5', 'Fmask']))
    try:
        return geemap.ee_to_df(period_table(col_all, fields, start, end))
    except ee.EEException as e:
        if len(batch_ids) > 1 and ('5000' in str(e) or 'accumulating' in str(e)):
            mid = len(batch_ids) // 2
            return pd.concat([fetch(batch_ids[:mid], start, end), fetch(batch_ids[mid:], start, end)], ignore_index=True)
        raise

# --- 3. Цикл по роках, місяцях і пачках полів ---
today = pd.Timestamp.today()
rows = []
for year in range(START_YEAR, today.year + 1):
    n = 0
    for month in range(1, 13):
        start = pd.Timestamp(year=year, month=month, day=1)
        if start > today:
            break
        end = start + pd.offsets.MonthBegin(1)
        for i in range(0, len(ids), BATCH):
            d = fetch(ids[i:i + BATCH], start.strftime('%Y-%m-%d'), end.strftime('%Y-%m-%d'))
            if len(d) and {'ndvi', 'cloud'} <= set(d.columns):
                rows.append(d[['field_id', 'date', 'ndvi', 'cloud']])
                n += len(d)
    print(f'{year}: записів {n}')

if not rows:
    raise RuntimeError('Немає даних: перевірте виведену кількість знімків над полями.')

daily = (pd.concat(rows, ignore_index=True)
         .rename(columns={'cloud': 'cloud_frac'})
         .sort_values(['field_id', 'date']))
daily['cloud_frac'] = daily['cloud_frac'].fillna(1.0)
daily.to_csv(OUT_DAILY, index=False)

# --- 4. Фільтр хмарності в полігоні + місячне середнє ---
ok = daily[(daily['cloud_frac'] < CLOUD_MAX) & daily['ndvi'].notna()].copy()
ok['month_key'] = ok['date'].str[:7]
monthly = (ok.groupby(['field_id', 'month_key'])
           .agg(ndvi_hls=('ndvi', 'mean'), n_obs=('ndvi', 'size'))
           .reset_index()
           .rename(columns={'month_key': 'date'}))
monthly['year'] = monthly['date'].str[:4].astype(int)
monthly['month'] = monthly['date'].str[5:7].astype(int)
monthly['ndvi_hls'] = monthly['ndvi_hls'].round(4)
monthly = monthly[['field_id', 'date', 'year', 'month', 'ndvi_hls', 'n_obs']]

monthly.to_csv(OUT_LONG, index=False)
monthly.pivot(index='field_id', columns='date', values='ndvi_hls').to_csv(OUT_WIDE)

print(monthly.head(12).to_string(index=False))
print('Рядків:', len(monthly), '| місяців:', monthly['date'].nunique(),
      '| полів:', monthly['field_id'].nunique())