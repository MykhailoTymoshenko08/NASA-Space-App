import math
import numpy as np
import pandas as pd
import geopandas as gpd

FIELDS_PATH = '/fields.geojson'      # field_id, crop, geometry
TERRAIN_CSV = 'terrain2.csv'         # field_id, slope_pct, slope_pct_p90
OUT_CSV = 'fields_filtered.csv'

SLOPE_COL = 'slope_pct_p90'

SLOPE_COL = 'slope_deg_p90'     # або 'slope_deg' (медіана)
SLOPE_LIMIT_DEG = 5.0

ROW_CROPS = {'Corn', 'Soybeans', 'Cotton', 'Sorghum', 'Sugarbeets', 'Potatoes'}
NON_ROW_CROPS = {'Winter Wheat', 'Alfalfa', 'Barley', 'Oats'}

def slope_filter(crop, slope_deg):
    """Повертає (F, причина). F=0 для просапних, якщо схил > 5°."""
    if pd.isna(slope_deg):
        return np.nan, 'no slope data'
    if crop in ROW_CROPS:
        if slope_deg > SLOPE_LIMIT_DEG:
            return 0.0, f'row crop, slope > {SLOPE_LIMIT_DEG}° (erosion risk)'
        return 1.0, 'row crop, slope OK'
    if crop in NON_ROW_CROPS:
        return 1.0, 'non-row crop, not limited by slope'
    return np.nan, 'unknown crop'

# 1. Таблиця полів + рельєф
fields = gpd.read_file(FIELDS_PATH)[['field_id', 'crop']]
terrain = pd.read_csv(TERRAIN_CSV)
df = fields.merge(terrain, on='field_id', how='left')

# 2. Застосування правил
res = df.apply(lambda r: slope_filter(r['crop'], r[SLOPE_COL]), axis=1, result_type='expand')
df['F_slope'] = res[0]
df['reason'] = res[1]

df.to_csv(OUT_CSV, index=False)
print(df.to_string(index=False))

unknown = df.loc[df['reason'] == 'unknown crop', 'crop'].unique()
if len(unknown):
    print('\nНевідомі культури (перевір написання):', unknown)