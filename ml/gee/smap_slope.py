import math
import ee
import geemap
import geopandas as gpd
import pandas as pd

ee.Authenticate()
ee.Initialize(project='ee-kokoshalina')

FIELDS_PATH = 'fields.geojson'      # field_id, crop, geometry
OUT_CSV = '/terrain2.csv'
BATCH = 300                         # fields per request (GEE returns at most 5000 records per getInfo)

# 1. Поля -> ee.FeatureCollection (тільки field_id + геометрія)
gdf = gpd.read_file(FIELDS_PATH).to_crs(4326)
ids = gdf['field_id'].astype(str).tolist()
gdf['field_id'] = gdf['field_id'].astype(str)
fields_fc = geemap.gdf_to_ee(gdf[['field_id', 'geometry']])

# 2. NASADEM (30 м) -> схил у градусах
nasadem = ee.Image('NASA/NASADEM_HGT/001').select('elevation')
slope_deg_img = ee.Terrain.slope(nasadem).rename('slope_deg')

# 3. Медіана + 90-й перцентиль з явними назвами колонок
reducer = (
    ee.Reducer.median().setOutputs(['slope_deg'])
    .combine(ee.Reducer.percentile([90], ['slope_deg_p90']), sharedInputs=True)
)

# processed in batches of BATCH fields: a single ee_to_df on ~26 000 demo fields hits the 5000-record limit
frames = []
for i in range(0, len(ids), BATCH):
    batch_fc = fields_fc.filter(ee.Filter.inList('field_id', ids[i:i + BATCH]))
    stats_fc = slope_deg_img.reduceRegions(collection=batch_fc, reducer=reducer, scale=30)
    frames.append(geemap.ee_to_df(stats_fc)[['field_id', 'slope_deg', 'slope_deg_p90']])
    print(f'batch {i // BATCH + 1} / {-(-len(ids) // BATCH)} done')

# 4. У pandas -> CSV
df = pd.concat(frames, ignore_index=True)
df[['slope_deg', 'slope_deg_p90']] = df[['slope_deg', 'slope_deg_p90']].round(2)
df.to_csv(OUT_CSV, index=False)
print(df)