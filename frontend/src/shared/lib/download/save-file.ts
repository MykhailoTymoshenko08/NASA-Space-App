/**
 * Hand a file to the browser's download flow (desktop: Downloads folder; phones: the share or open sheet).
 * The object URL is revoked after the click has been handled, so the blob is not kept in memory.
 */
export function saveFile(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.rel = "noopener";
  a.style.display = "none";
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 30_000);
}
